#!/usr/bin/env node
/**
 * 版本号递增脚本（前后端独立版本）
 *
 * 依据 git 变更范围自动判断：
 *   - backend/**  变更 → 后端版本 patch +1
 *   - frontend/** 变更 → 前端版本 patch +1
 *
 * 用法：
 *   node scripts/bump-version.mjs          # 按改动范围递增
 *   node scripts/bump-version.mjs --all    # 前后端都 +1
 *   node scripts/bump-version.mjs --backend
 *   node scripts/bump-version.mjs --frontend
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const backendFile = path.join(root, 'backend/internal/version/version.go');
const frontendFile = path.join(root, 'frontend/src/version.json');
const frontendPackage = path.join(root, 'frontend/package.json');

function readVersionFromGo() {
  const text = fs.readFileSync(backendFile, 'utf8');
  const matched = text.match(/Version\s*=\s*"([^"]+)"/);

  return matched ? matched[1] : '1.0.0';
}

function readFrontendVersion() {
  if (!fs.existsSync(frontendFile)) return '1.0.0';

  try {
    return JSON.parse(fs.readFileSync(frontendFile, 'utf8')).version || '1.0.0';
  } catch (e) {
    return '1.0.0';
  }
}

function nextVersion(version) {
  const parts = String(version)
    .split('.')
    .map((item) => Number.parseInt(item, 10) || 0);

  while (parts.length < 3) parts.push(0);
  parts[2] += 1;

  return parts.join('.');
}

// 北京时间，精确到秒
function nowText() {
  const formatter = new Intl.DateTimeFormat('en-CA', {
    timeZone: 'Asia/Shanghai',
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
    hour: '2-digit',
    minute: '2-digit',
    second: '2-digit',
    hour12: false,
  });

  const parts = Object.fromEntries(formatter.formatToParts(new Date()).map((item) => [item.type, item.value]));

  return `${parts.year}-${parts.month}-${parts.day} ${parts.hour}:${parts.minute}:${parts.second}`;
}

function changedPaths() {
  try {
    const output = execFileSync('git', ['status', '--porcelain'], { cwd: root, encoding: 'utf8' });
    const paths = [];

    for (const line of output.split('\n').filter(Boolean)) {
      const raw = line.slice(3).trim();

      if (raw.includes(' -> ')) {
        // 重命名：old -> new
        raw.split(' -> ').forEach((item) => paths.push(item.trim()));
      } else {
        paths.push(raw);
      }
    }

    return paths.map((item) => item.replace(/^"|"$/g, ''));
  } catch (e) {
    return [];
  }
}

const args = process.argv.slice(2);
const changed = changedPaths();

const explicitBackend = args.includes('--backend');
const explicitFrontend = args.includes('--frontend');
const explicitAll = args.includes('--all');
const explicitOnly = explicitBackend || explicitFrontend || explicitAll;

// 显式指定 --backend / --frontend 时只递增指定的一侧，避免误伤另一边
const backendChanged =
  explicitAll ||
  explicitBackend ||
  (!explicitOnly && changed.some((item) => item.startsWith('backend/')));
const frontendChanged =
  explicitAll ||
  explicitFrontend ||
  (!explicitOnly && changed.some((item) => item.startsWith('frontend/')));

const releasedAt = nowText();
const result = {};

if (backendChanged) {
  const version = nextVersion(readVersionFromGo());

  fs.writeFileSync(
    backendFile,
    `// Code generated by scripts/bump-version.mjs; DO NOT EDIT.\npackage version\n\n// 后端版本号与发布时间（北京时间）\nvar (\n\tVersion    = "${version}"\n\tReleasedAt = "${releasedAt}"\n)\n`,
    'utf8',
  );

  result.backend = version;
}

if (frontendChanged) {
  const version = nextVersion(readFrontendVersion());

  fs.writeFileSync(
    frontendFile,
    `${JSON.stringify({ version, released_at: releasedAt }, null, 2)}\n`,
    'utf8',
  );

  const pkg = JSON.parse(fs.readFileSync(frontendPackage, 'utf8'));
  pkg.version = version;
  fs.writeFileSync(frontendPackage, `${JSON.stringify(pkg, null, 2)}\n`, 'utf8');

  result.frontend = version;
}

if (Object.keys(result).length === 0) {
  console.log('未检测到 backend/ 或 frontend/ 变更，版本号保持不变');
} else {
  if (result.backend) console.log(`后端版本 → ${result.backend}（${releasedAt}）`);
  if (result.frontend) console.log(`前端版本 → ${result.frontend}（${releasedAt}）`);
}
