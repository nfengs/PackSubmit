-- 包装确认单字段扩展（在已有库上执行）
ALTER TABLE `pf_pack_proposal`
  ADD COLUMN `write_date` date DEFAULT NULL COMMENT '填写日期' AFTER `description`,
  ADD COLUMN `project_model` varchar(100) NOT NULL DEFAULT '' COMMENT '项目车型' AFTER `write_date`,
  ADD COLUMN `part_name` varchar(200) NOT NULL DEFAULT '' COMMENT '零件名称' AFTER `project_model`,
  ADD COLUMN `part_no` varchar(100) NOT NULL DEFAULT '' COMMENT '零件号' AFTER `part_name`,
  ADD COLUMN `part_material` varchar(100) NOT NULL DEFAULT '' COMMENT '零件材料' AFTER `part_no`,
  ADD COLUMN `customer_address` varchar(255) NOT NULL DEFAULT '' COMMENT '客户地址' AFTER `part_material`,
  ADD COLUMN `customer_contact` varchar(50) NOT NULL DEFAULT '' COMMENT '客户联系人' AFTER `customer_address`,
  ADD COLUMN `customer_phone` varchar(30) NOT NULL DEFAULT '' COMMENT '客户电话' AFTER `customer_contact`,
  ADD COLUMN `customer_email` varchar(100) NOT NULL DEFAULT '' COMMENT '客户邮箱' AFTER `customer_phone`,
  ADD COLUMN `customer_fax` varchar(30) NOT NULL DEFAULT '' COMMENT '客户传真' AFTER `customer_email`,
  ADD COLUMN `supplier_code` varchar(50) NOT NULL DEFAULT '' COMMENT '供应商代码' AFTER `customer_fax`,
  ADD COLUMN `supplier_address` varchar(255) NOT NULL DEFAULT '' COMMENT '供应商地址' AFTER `supplier_code`,
  ADD COLUMN `supplier_email` varchar(100) NOT NULL DEFAULT '' COMMENT '供应商邮箱' AFTER `supplier_address`,
  ADD COLUMN `supplier_fax` varchar(30) NOT NULL DEFAULT '' COMMENT '供应商传真' AFTER `supplier_email`,
  ADD COLUMN `pack_box_no` varchar(50) NOT NULL DEFAULT '' COMMENT '包装箱编号' AFTER `supplier_fax`,
  ADD COLUMN `pack_material` varchar(20) NOT NULL DEFAULT '' COMMENT '包装箱材料 plastic/metal/carton/other' AFTER `pack_box_no`,
  ADD COLUMN `part_weight` decimal(10,3) NOT NULL DEFAULT 0 COMMENT '产品净重kg' AFTER `pack_material`,
  ADD COLUMN `part_size_l` decimal(10,2) NOT NULL DEFAULT 0 COMMENT '产品外形长mm' AFTER `part_weight`,
  ADD COLUMN `part_size_w` decimal(10,2) NOT NULL DEFAULT 0 COMMENT '产品外形宽mm' AFTER `part_size_l`,
  ADD COLUMN `part_size_h` decimal(10,2) NOT NULL DEFAULT 0 COMMENT '产品外形高mm' AFTER `part_size_w`,
  ADD COLUMN `box_size_l` decimal(10,2) NOT NULL DEFAULT 0 COMMENT '包装箱外长mm' AFTER `part_size_h`,
  ADD COLUMN `box_size_w` decimal(10,2) NOT NULL DEFAULT 0 COMMENT '包装箱外宽mm' AFTER `box_size_l`,
  ADD COLUMN `box_size_h` decimal(10,2) NOT NULL DEFAULT 0 COMMENT '包装箱外高mm' AFTER `box_size_w`,
  ADD COLUMN `gross_weight` decimal(10,3) NOT NULL DEFAULT 0 COMMENT '毛重kg' AFTER `box_size_h`,
  ADD COLUMN `returnable` tinyint unsigned NOT NULL DEFAULT 1 COMMENT '包装箱是否返回 1是 0否' AFTER `gross_weight`,
  ADD COLUMN `dunnage_returnable` tinyint unsigned NOT NULL DEFAULT 1 COMMENT '内衬是否返回 1是 0否' AFTER `returnable`,
  ADD COLUMN `packing_qty` int unsigned NOT NULL DEFAULT 0 COMMENT '存放数量(件/箱)' AFTER `dunnage_returnable`,
  ADD COLUMN `pallet_size_l` decimal(10,2) NOT NULL DEFAULT 0 COMMENT '满托盘长mm' AFTER `packing_qty`,
  ADD COLUMN `pallet_size_w` decimal(10,2) NOT NULL DEFAULT 0 COMMENT '满托盘宽mm' AFTER `pallet_size_l`,
  ADD COLUMN `pallet_size_h` decimal(10,2) NOT NULL DEFAULT 0 COMMENT '满托盘高mm' AFTER `pallet_size_w`,
  ADD COLUMN `pallet_layer_qty` int unsigned NOT NULL DEFAULT 0 COMMENT '每层包装数量' AFTER `pallet_size_h`,
  ADD COLUMN `pallet_layer_count` int unsigned NOT NULL DEFAULT 0 COMMENT '堆码层数' AFTER `pallet_layer_qty`,
  ADD COLUMN `pallet_parts_qty` int unsigned NOT NULL DEFAULT 0 COMMENT '每托盘零件数量' AFTER `pallet_layer_count`,
  ADD COLUMN `packaging_instruction` text COMMENT '包装操作说明' AFTER `pallet_parts_qty`;

ALTER TABLE `pf_attachment`
  ADD COLUMN `attach_type` varchar(20) NOT NULL DEFAULT 'attachment' COMMENT '附件类型 part/inner/final/packaging/attachment' AFTER `proposal_id`;
